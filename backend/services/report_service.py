def generate_pdf_report(db, name: str, report_type: str, filters: dict = None) -> dict:
    """
    Generate a PDF report with analytics data.
    
    Args:
        db: MongoDB database instance
        name: Report name
        report_type: Type of report (PDF, Excel, etc.)
        filters: Optional filters for data
        
    Returns:
        Report metadata dict with fileName, filePath, fileSize, type, status
        
    Raises:
        ValueError: If report generation fails
    """
    try:
        os.makedirs(ActiveConfig.REPORTS_DIR, exist_ok=True)

        # Fetch data
        stats = get_dashboard_stats(db)
        analytics = get_analytics_data(db, filters)

        # Generate unique filename
        filename = f"{name.replace(' ', '_')}_{uuid.uuid4().hex[:8]}.pdf"
        filepath = os.path.join(ActiveConfig.REPORTS_DIR, filename)

        # Build PDF
        doc = SimpleDocTemplate(filepath, pagesize=A4)
        styles = getSampleStyleSheet()
        story = []

        # Header
        story.append(Paragraph(
            "<b>Smart Waste Management — Analytics Report</b>",
            styles['Title']
        ))
        story.append(Paragraph(
            f"Report: {name} | Type: {report_type} | Date: {datetime.utcnow().strftime('%d %B %Y')}",
            styles['Normal']
        ))
        story.append(Spacer(1, 20))

        # Executive Summary
        story.append(Paragraph("<b>Executive Summary</b>", styles['Heading2']))
        summary_data = [
            ["Metric", "Value"],
            ["Total Waste Generated", f"{stats.get('totalWasteGenerated', 0):,.2f} Tons/Day"],
            ["Average Recycling Rate", f"{stats.get('avgRecyclingRate', 0):.2f}%"],
            ["Total Cities Monitored", str(stats.get('totalCities', 0))],
            ["Avg Management Cost", f"₹{stats.get('avgManagementCost', 0):,.2f}/Ton"],
            ["Municipal Efficiency", f"{stats.get('municipalEfficiencyScore', 0):.2f}/10"],
            ["Total Records", str(stats.get('totalRecords', 0))],
        ]
        summary_table = Table(summary_data, colWidths=[200, 200])
        summary_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#10b981')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 10),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#f0fdf4')),
        ]))
        story.append(summary_table)
        story.append(Spacer(1, 20))

        # Waste by Type
        story.append(Paragraph("<b>Waste Generated by Type</b>", styles['Heading2']))
        type_data = [["Waste Type", "Total (Tons/Day)", "Avg Recycling %"]]
        for item in analytics.get("wasteByType", []):
            type_data.append([
                item["type"],
                f"{item['totalWaste']:,.2f}",
                f"{item['avgRecycling']:.2f}%"
            ])
        type_table = Table(type_data, colWidths=[150, 150, 150])
        type_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#3b82f6')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#eff6ff')),
        ]))
        story.append(type_table)
        story.append(Spacer(1, 20))

        # Top Cities
        story.append(Paragraph("<b>Top Cities by Waste Generation</b>", styles['Heading2']))
        city_data = [["City", "Total Waste", "Recycling Rate"]]
        for item in analytics.get("wasteByCity", [])[:10]:
            city_data.append([
                item["city"],
                f"{item['totalWaste']:,.2f}",
                f"{item['avgRecycling']:.2f}%"
            ])
        city_table = Table(city_data, colWidths=[180, 120, 120])
        city_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f59e0b')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
            ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#fffbeb')),
        ]))
        story.append(city_table)

        # Build PDF
        doc.build(story)
        file_size = os.path.getsize(filepath)

        # Save report metadata
        report_doc = create_report_document(
            name=name,
            report_type=report_type,
            filters=filters or {},
            file_path=filepath,
            file_size=f"{file_size / 1024:.1f} KB"
        )
        db["reports"].insert_one(report_doc)

        logger.info(f"PDF report generated: {filepath}")
        return {
            "fileName": filename,
            "filePath": filepath,
            "fileSize": f"{file_size / 1024:.1f} KB",
            "type": "PDF",
            "status": "Ready"
        }

    except Exception as e:
        logger.error(f"Error generating PDF report: {e}", exc_info=True)
        raise ValueError(f"Failed to generate PDF report: {str(e)}")


def generate_excel_report(db, name: str, report_type: str, filters: dict = None) -> dict:
    """
    Generate an Excel report with multiple sheets.
    
    Args:
        db: MongoDB database instance
        name: Report name
        report_type: Type of report (PDF, Excel, etc.)
        filters: Optional filters for data
        
    Returns:
        Report metadata dict with fileName, filePath, fileSize, type, status
        
    Raises:
        ValueError: If report generation fails
    """
    try:
        os.makedirs(ActiveConfig.REPORTS_DIR, exist_ok=True)

        stats = get_dashboard_stats(db)
        analytics = get_analytics_data(db, filters)

        filename = f"{name.replace(' ', '_')}_{uuid.uuid4().hex[:8]}.xlsx"
        filepath = os.path.join(ActiveConfig.REPORTS_DIR, filename)

        wb = Workbook()

        # Sheet 1: Executive Summary
        ws1 = wb.active
        ws1.title = "Executive Summary"
        ws1.append(["Smart Waste Management Analytics Report"])
        ws1.append([])
        ws1.append(["Metric", "Value"])
        ws1.append(["Total Waste Generated", f"{stats.get('totalWasteGenerated', 0):,.2f} Tons/Day"])
        ws1.append(["Average Recycling Rate", f"{stats.get('avgRecyclingRate', 0):.2f}%"])
        ws1.append(["Total Cities", str(stats.get('totalCities', 0))])
        ws1.append(["Avg Management Cost", f"₹{stats.get('avgManagementCost', 0):,.2f}/Ton"])
        ws1.append(["Municipal Efficiency", f"{stats.get('municipalEfficiencyScore', 0):.2f}/10"])
        ws1.column_dimensions['A'].width = 30
        ws1.column_dimensions['B'].width = 30

        # Sheet 2: Waste by Type
        ws2 = wb.create_sheet("Waste by Type")
        ws2.append(["Waste Type", "Total (Tons/Day)", "Avg Recycling %"])
        for item in analytics.get("wasteByType", []):
            ws2.append([item["type"], item["totalWaste"], f"{item['avgRecycling']:.2f}%"])
        ws2.column_dimensions['A'].width = 20
        ws2.column_dimensions['B'].width = 20
        ws2.column_dimensions['C'].width = 20

        # Sheet 3: Waste by City
        ws3 = wb.create_sheet("Waste by City")
        ws3.append(["City", "Total Waste", "Recycling Rate", "Efficiency"])
        for item in analytics.get("wasteByCity", []):
            ws3.append([
                item["city"],
                item["totalWaste"],
                f"{item['avgRecycling']:.2f}%",
                f"{item['avgEfficiency']:.2f}"
            ])
        ws3.column_dimensions['A'].width = 25
        ws3.column_dimensions['B'].width = 20
        ws3.column_dimensions['C'].width = 20
        ws3.column_dimensions['D'].width = 15

        # Sheet 4: Waste by Year
        ws4 = wb.create_sheet("Waste by Year")
        ws4.append(["Year", "Total Waste", "Avg Recycling", "Total Cost"])
        for item in analytics.get("wasteByYear", []):
            ws4.append([
                item["year"],
                item["totalWaste"],
                f"{item['avgRecycling']:.2f}%",
                item["totalCost"]
            ])
        ws4.column_dimensions['A'].width = 10
        ws4.column_dimensions['B'].width = 20

        # Styling
        header_fill = PatternFill(start_color='10b981', end_color='10b981', fill_type='solid')
        header_font = Font(bold=True, color='FFFFFF')
        for ws in [ws1, ws2, ws3, ws4]:
            for cell in ws[1]:
                cell.fill = header_fill
                cell.font = header_font
                cell.alignment = Alignment(horizontal='center')

        wb.save(filepath)
        file_size = os.path.getsize(filepath)

        report_doc = create_report_document(
            name=name,
            report_type=report_type,
            filters=filters or {},
            file_path=filepath,
            file_size=f"{file_size / 1024:.1f} KB"
        )
        db["reports"].insert_one(report_doc)

        logger.info(f"Excel report generated: {filepath}")
        return {
            "fileName": filename,
            "filePath": filepath,
            "fileSize": f"{file_size / 1024:.1f} KB",
            "type": "Excel",
            "status": "Ready"
        }

    except Exception as e:
        logger.error(f"Error generating Excel report: {e}", exc_info=True)
        raise ValueError(f"Failed to generate Excel report: {str(e)}")


def get_reports_list(db, limit: int = 50) -> list:
    """Fetch list of generated reports."""
    try:
        collection = db["reports"]
        cursor = collection.find().sort("createdAt", -1).limit(limit)
        reports = []
        for doc in cursor:
            reports.append({
                "id": str(doc["_id"]),
                "name": doc.get("name"),
                "type": doc.get("type"),
                "fileSize": doc.get("fileSize"),
                "status": doc.get("status"),
                "downloads": doc.get("downloads", 0),
                "createdAt": doc.get("createdAt").isoformat() if doc.get("createdAt") else "",
            })
        return reports
    except Exception as e:
        logger.error(f"Error fetching reports list: {e}", exc_info=True)
        return []


def download_report(db, report_id: str):
    """Download a report file by ID."""
    try:
        from bson import ObjectId
        collection = db["reports"]
        doc = collection.find_one({"_id": ObjectId(report_id)})
        if not doc:
            return None, None

        filepath = doc.get("filePath")
        if not filepath or not os.path.exists(filepath):
            return None, None

        # Increment download count
        collection.update_one(
            {"_id": ObjectId(report_id)},
            {"$inc": {"downloads": 1}}
        )

        return filepath, doc.get("fileName")
    except Exception as e:
        logger.error(f"Error downloading report: {e}", exc_info=True)
        return None, None
